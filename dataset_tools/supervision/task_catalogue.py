def get_task_definition(task_id: str) -> TaskDefinition:
    """Récupère la définition d'une tâche avec validation."""
    if task_id not in TASK_CATALOGUE:
        raise KeyError(f"Tâche inconnue dans le catalogue ARCHI-AI: {task_id}")
    return TASK_CATALOGUE[task_id]


def list_tasks_by_group(group: TaskGroup) -> List[TaskDefinition]:
    """Retourne toutes les tâches d'un groupe donné."""
    return [t for t in TASK_CATALOGUE.values() if t.group == group]
